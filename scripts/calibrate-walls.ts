/**
 * Fits the wave lab's walls (lib/wifi-walls.ts, generated). For each wall type
 * and band it finds the wave impedance z and per-step loss k that make one
 * head-on crossing in the simulation (lib/wifi-replica, a 1D copy of the GPU
 * update) transmit WALL_LOSS_DB and reflect what ITU-R P.2040 predicts
 * (lib/wall-physics). Values are snapped to the texture encoding before the
 * final measurement, so the file states what the GPU actually runs.
 *
 *   npm run calibrate:walls      (≈ 3 minutes)
 */
import { writeFileSync } from "node:fs"
import { BAND_IDS, MATERIAL_IDS, WALL_LOSS_DB } from "../lib/wifi"
import { wallReflectionTable } from "../lib/wall-physics"
import { replicaWall } from "../lib/wifi-replica"
import { WALL_CELLS, WAVELENGTH_CELLS, Z_MAX, dampByte, dampOf, zByte, zOf } from "../lib/wifi-sim"

const reflect = wallReflectionTable()
const round = (v: number, d = 4) => Number(v.toFixed(d))

/** Loss k that gives transmission loss `t` dB at impedance z (t rises with k). */
function kFor(lam: number, cells: number, z: number, t: number): number {
  let lo = 0
  let hi = 1
  for (let i = 0; i < 18; i++) {
    const m = (lo + hi) / 2
    if (replicaWall(lam, cells, z, m).t < t) lo = m
    else hi = m
  }
  return (lo + hi) / 2
}

const rows: string[] = []
for (const m of MATERIAL_IDS) {
  const cols: string[] = []
  for (const b of BAND_IDS) {
    const lam = WAVELENGTH_CELLS[b]
    const cells = WALL_CELLS[m]
    const tT = WALL_LOSS_DB[m][b]
    const tR = reflect[m][b]
    const at = (z: number) => ({ z, k: kFor(lam, cells, z, tT) })
    // Loss alone already reflects some; add impedance until the reflection matches.
    let best = at(1)
    if (replicaWall(lam, cells, best.z, best.k).r < tR) {
      let lo = 1
      let hi = Z_MAX
      for (let i = 0; i < 16; i++) {
        const mid = (lo + hi) / 2
        const c = at(mid)
        if (replicaWall(lam, cells, c.z, c.k).r < tR) lo = mid
        else hi = mid
      }
      best = at((lo + hi) / 2)
    }
    const z = zOf(zByte(best.z))
    const k = dampOf(dampByte(best.k))
    const got = replicaWall(lam, cells, z, k)
    console.log(`${m.padEnd(9)} ${b}: z ${z.toFixed(3)} k ${k.toFixed(4)}  R ${got.r.toFixed(1)} (target ${tR.toFixed(1)})  T ${got.t.toFixed(1)} (target ${tT})`)
    cols.push(`${b}: { z: ${round(z)}, k: ${round(k)}, r: ${round(got.r, 2)}, t: ${round(got.t, 2)} }`)
  }
  rows.push(`  ${m}: { ${cols.join(", ")} },`)
}

writeFileSync(
  new URL("../lib/wifi-walls.ts", import.meta.url),
  `// Generated by scripts/calibrate-walls.ts (npm run calibrate:walls). Do not edit.
import type { BandId, MaterialId } from "./wifi"

/**
 * Per wall type and band: z = wave impedance vs air, k = per-step loss (both
 * as the GPU texture encodes them), and what one head-on crossing then does
 * in the simulation: r = power reflected, dB; t = transmission loss, dB.
 */
export type WallMedium = { z: number; k: number; r: number; t: number }

export const WALL_MEDIUM: Record<MaterialId, Record<BandId, WallMedium>> = {
${rows.join("\n")}
}
`
)
